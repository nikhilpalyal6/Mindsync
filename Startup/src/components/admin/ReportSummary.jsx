import React from 'react';
import { FileText, Calendar, CheckSquare, Clock, Shield } from 'lucide-react';

export const ReportSummary = React.memo(({ summary }) => {
  if (!summary) return null;

  const formatDate = (dateStr) => {
    if (!dateStr) return 'N/A';
    return new Date(dateStr).toLocaleString(undefined, {
      year: 'numeric',
      month: 'short',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit'
    });
  };

  const cards = [
    {
      title: 'Report Type',
      value: summary.reportType ? summary.reportType.toUpperCase() + ' REPORT' : 'N/A',
      icon: FileText,
      color: '#3b82f6'
    },
    {
      title: 'Total Records',
      value: summary.totalRecords !== undefined ? summary.totalRecords.toLocaleString() : '0',
      icon: CheckSquare,
      color: '#10b981'
    },
    {
      title: 'Date Window',
      value: summary.dateRange || 'N/A',
      icon: Calendar,
      color: '#f59e0b'
    },
    {
      title: 'Generated At',
      value: formatDate(summary.generatedAt),
      icon: Clock,
      color: '#a78bfa'
    },
    {
      title: 'Generated By',
      value: summary.generatedBy || 'System Administrator',
      icon: Shield,
      color: '#ef4444'
    }
  ];

  return (
    <div style={{
      display: 'grid',
      gridTemplateColumns: 'repeat(auto-fit, minmax(200px, 1fr))',
      gap: '16px',
      width: '100%',
      marginBottom: '20px'
    }}>
      {cards.map((card, idx) => {
        const Icon = card.icon;
        return (
          <div key={idx} className="admin-card" style={{ display: 'flex', flexDirection: 'column', gap: '8px', padding: '16px', minHeight: '100px', justifyContent: 'center' }}>
            <div style={{ display: 'flex', alignItems: 'center', gap: '8px', color: 'var(--admin-text-muted)', fontSize: '0.725rem', fontWeight: 600, textTransform: 'uppercase', letterSpacing: '0.025em' }}>
              <Icon size={14} style={{ color: card.color }} />
              <span>{card.title}</span>
            </div>
            <span style={{ fontSize: '1rem', fontWeight: 700, color: '#fff', overflow: 'hidden', textOverflow: 'ellipsis', whiteSpace: 'nowrap' }} title={card.value}>
              {card.value}
            </span>
          </div>
        );
      })}
    </div>
  );
});

ReportSummary.displayName = 'ReportSummary';
export default ReportSummary;
